package ingress

import (
	"fmt"
	"log/slog"
	"os"
	"sort"
	"strings"
)

// GeneratorConfig holds the environment-level configuration for Caddyfile generation.
type GeneratorConfig struct {
	BaseDomain        string   // e.g., "example.com" or "lab.example.com" — used for cookie domain
	AdminEmail        string   // ACME registration email
	SuperAdmins       []string // Platform superadmin emails (get superadmin role on ALL apps)
	DefaultRPS        int      // Default rate limit
	CaddyfileBasePath string   // Path to Caddyfile.base (optional)
	AuthDomain        string   // Absolute FQDN for auth portal (e.g., "auth.a.styrman.io")
	ShellDomain       string   // Absolute FQDN for shell (e.g., "shell.a.styrman.io")
	AppsDomain        string   // Wildcard base for user apps (e.g., "apps.a.styrman.io")
	PreviewDomain     string   // Public preview wildcard base (e.g., "public.crew.styrman.xyz"); empty = off
	PrivateDomain     string   // Email-gated preview wildcard base (e.g., "private.crew.styrman.xyz"); empty = off
	IngressToken      string   // shared secret injected as X-Styrman-Ingress (proves ingress origin)
	JWTKey            string   // stable HMAC key so caddy-security JWTs survive restarts (else sessions break on redeploy)
	// AdminListen is the admin API's bind address. It is emitted into the
	// generated global options so the endpoint accepts requests only from
	// itself — see writeGlobalOptions.
	AdminListen string
}

// GenerateCaddyfile produces a complete Caddyfile from a list of discovered apps
// and the environment configuration. If a Caddyfile.base exists, its content is
// prepended to the generated output.
func GenerateCaddyfile(apps []App, cfg GeneratorConfig) string {
	var b strings.Builder

	// Prepend Caddyfile.base if it exists
	if cfg.CaddyfileBasePath != "" {
		baseContent, err := os.ReadFile(cfg.CaddyfileBasePath)
		if err != nil && !os.IsNotExist(err) {
			// Log non-trivial errors (permission denied, etc.) but continue
			slog.Warn("failed to read Caddyfile.base", "path", cfg.CaddyfileBasePath, "error", err)
		}
		if err == nil && len(baseContent) > 0 {
			b.WriteString("# ─── FROM Caddyfile.base (user-maintained) ───\n\n")
			b.Write(baseContent)
			b.WriteString("\n\n")
		}
	}

	b.WriteString("# ─── GENERATED by caddy-ingress (do not edit below) ───\n\n")

	// Determine if any app needs OAuth (non-public)
	needsOAuth := false
	for _, app := range apps {
		if app.Mode != ModePublic {
			needsOAuth = true
			break
		}
	}

	// Global options block
	writeGlobalOptions(&b, apps, cfg, needsOAuth)

	// HTTP → HTTPS redirect
	b.WriteString("# HTTP → HTTPS (always)\nhttp:// {\n    redir https://{host}{uri} permanent\n}\n\n")

	// Auth portal (only if OAuth is needed)
	if needsOAuth {
		fmt.Fprintf(&b, "# Auth portal\n%s {\n    authenticate with myportal\n}\n\n", cfg.AuthDomain)
	}

	// Sort apps by hostname for deterministic output
	sorted := make([]App, len(apps))
	copy(sorted, apps)
	sort.Slice(sorted, func(i, j int) bool {
		return sorted[i].Hostname < sorted[j].Hostname
	})

	// Per-app site blocks
	for _, app := range sorted {
		writeAppBlock(&b, app, cfg)
	}

	// Preview wildcards (*.PREVIEW_DOMAIN public, *.PRIVATE_DOMAIN OAuth-gated)
	// → the styrman server. ONE target backs both — picking independently
	// could split them across two labeled containers. The server validates
	// the per-link token itself; the token is carried in the subdomain (Host
	// preserved). The private block additionally requires an authenticated
	// app (it reuses the app's authorization policy, which only exists for
	// non-public apps).
	if cfg.PreviewDomain != "" || cfg.PrivateDomain != "" {
		var target *App
		for i := range sorted {
			if sorted[i].PreviewTarget {
				target = &sorted[i]
				break
			}
		}
		switch {
		case target == nil:
			slog.Warn("preview/private domain set but no container carries caddy_preview_target — wildcard blocks not emitted",
				"preview", cfg.PreviewDomain, "private", cfg.PrivateDomain)
		default:
			if cfg.PreviewDomain != "" {
				writePreviewWildcard(&b, *target, cfg)
			}
			if cfg.PrivateDomain != "" {
				if target.Mode == ModePublic {
					slog.Warn("PRIVATE_DOMAIN set but the preview target app is public (no auth policy) — private wildcard not emitted",
						"private", cfg.PrivateDomain, "app", target.Hostname)
				} else {
					writePrivateWildcard(&b, *target, cfg)
				}
			}
		}
	}

	return b.String()
}

// writePreviewWildcard emits the public *.PREVIEW_DOMAIN block that fronts the
// styrman server for capability links. No OAuth (the unguessable token IS the
// credential); client-supplied identity headers are stripped and the ingress
// token is injected so the server knows the request came through the ingress.
func writePreviewWildcard(b *strings.Builder, app App, cfg GeneratorConfig) {
	fmt.Fprintf(b, "# public preview links (*.%s → styrman server, no auth)\n", cfg.PreviewDomain)
	fmt.Fprintf(b, "*.%s {\n", cfg.PreviewDomain)
	fmt.Fprintf(b, "    rate_limit {\n")
	fmt.Fprintf(b, "        zone preview_rl {\n")
	fmt.Fprintf(b, "            key {remote_host}\n")
	fmt.Fprintf(b, "            events %d\n", cfg.DefaultRPS)
	fmt.Fprintf(b, "            window 1s\n")
	fmt.Fprintf(b, "        }\n")
	fmt.Fprintf(b, "    }\n")
	// Strip any client-supplied identity; the preview host must never carry one.
	for _, h := range []string{HeaderEmail, HeaderUser, HeaderRole, HeaderSubject, HeaderIngress} {
		fmt.Fprintf(b, "    request_header -%s\n", h)
	}
	// The portal's session cookie is scoped to the base domain, so a browser
	// sends it to the public preview host too — and the preview tunnels the
	// request into a guest app someone else runs. Cut that one cookie out of
	// the header (the guest app's own cookies must survive, so the whole
	// header cannot go) — audit 2026-09-13.
	fmt.Fprintf(b, "    request_header Cookie \"(?:^|;\\s*)%s=[^;]*\" \"\"\n", AuthCookieName)
	if cfg.IngressToken != "" {
		fmt.Fprintf(b, "    request_header %s %q\n", HeaderIngress, cfg.IngressToken)
	}
	// Preserve the incoming Host so the server can read the <token> subdomain.
	fmt.Fprintf(b, "    reverse_proxy %s:%d {\n", app.ContainerIP, app.Port)
	fmt.Fprintf(b, "        header_up Host {host}\n")
	fmt.Fprintf(b, "    }\n")
	b.WriteString("}\n\n")
}

// writePrivateWildcard emits the OAuth-gated *.PRIVATE_DOMAIN block fronting
// the styrman server for email-gated share links. Reuses the target app's
// authorization policy (the JWT cookie is domain-scoped, so a session from any
// styrman host is valid here); injects the verified identity headers exactly
// like an authenticated app block, and preserves Host so the server can read
// the <token> subdomain.
func writePrivateWildcard(b *strings.Builder, app App, cfg GeneratorConfig) {
	policyName := sanitizePolicyName(app.Hostname)
	fmt.Fprintf(b, "# private share links (*.%s → styrman server, Google OAuth)\n", cfg.PrivateDomain)
	fmt.Fprintf(b, "*.%s {\n", cfg.PrivateDomain)
	fmt.Fprintf(b, "    rate_limit {\n")
	fmt.Fprintf(b, "        zone private_rl {\n")
	fmt.Fprintf(b, "            key {remote_host}\n")
	fmt.Fprintf(b, "            events %d\n", cfg.DefaultRPS)
	fmt.Fprintf(b, "            window 1s\n")
	fmt.Fprintf(b, "        }\n")
	fmt.Fprintf(b, "    }\n")
	b.WriteString("    route {\n")
	// Strip CLIENT-supplied copies of the upstream claim headers before the
	// authorizer injects the authentic ones (same defense as writeAppBlock).
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderEmail)
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderName)
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderRoles)
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderSub)
	fmt.Fprintf(b, "        authorize with %s_policy\n", policyName)
	// Clean identity headers from the injected claims.
	fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderEmail, UpstreamHeaderEmail)
	fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderUser, UpstreamHeaderName)
	fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderSubject, UpstreamHeaderSub)
	fmt.Fprintf(b, "        request_header %s \"%s\"\n", HeaderRole, RoleUser)
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderEmail)
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderName)
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderRoles)
	fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderSub)
	// Strip any client-supplied ingress token unconditionally, THEN inject the
	// real one — safe even in a half-configured deploy with no token set.
	fmt.Fprintf(b, "        request_header -%s\n", HeaderIngress)
	if cfg.IngressToken != "" {
		fmt.Fprintf(b, "        request_header %s %q\n", HeaderIngress, cfg.IngressToken)
	}
	// Preserve the incoming Host so the server can read the <token> subdomain.
	fmt.Fprintf(b, "        reverse_proxy %s:%d {\n", app.ContainerIP, app.Port)
	fmt.Fprintf(b, "            header_up Host {host}\n")
	fmt.Fprintf(b, "        }\n")
	b.WriteString("    }\n}\n\n")
}

// writeGlobalOptions writes the global options block including ACME, directive
// ordering, and security config.
func writeGlobalOptions(b *strings.Builder, apps []App, cfg GeneratorConfig, needsOAuth bool) {
	b.WriteString("{\n")
	fmt.Fprintf(b, "    email %s\n", cfg.AdminEmail)
	b.WriteString("    acme_dns cloudflare {env.CLOUDFLARE_API_TOKEN}\n")
	b.WriteString("    auto_https disable_redirects\n\n")

	// The admin API reconfigures the ENTIRE ingress in a network_mode:host
	// process holding the docker socket, so its exposure is a host-root path.
	// The `admin <addr>` line is a REAL control: every /load REPLACES the admin
	// server per the loaded config, and a config that omits the block can move
	// the listener off loopback — observed live 2026-09-01, when a failed boot
	// load left the admin on 0.0.0.0:<random> with host checking disabled.
	// Emitting the loopback pin in every generated config forecloses that,
	// alongside the loadConfig loopback-bind guard and the >=2.11.4 Caddy
	// floor (GO-2026-4537 / GO-2026-5743). The `origins` line, by contrast, is
	// browser-only defense-in-depth: Caddy consults it solely when a request
	// carries an Origin/Sec-* header, so it does NOT gate a header-less local
	// `curl` and does not, on its own, make /load caller-bound.
	if cfg.AdminListen != "" {
		fmt.Fprintf(b, "    admin %s {\n        origins %s\n    }\n\n", cfg.AdminListen, cfg.AdminListen)
	}

	b.WriteString("    order rate_limit before basicauth\n")
	if needsOAuth {
		b.WriteString("    order authenticate before respond\n")
		b.WriteString("    order authorize before reverse_proxy\n")
	}
	b.WriteString("\n")

	// Prometheus metrics at admin API (:2019/metrics)
	b.WriteString("    metrics {\n")
	b.WriteString("        per_host\n")
	b.WriteString("    }\n")

	if needsOAuth {
		b.WriteString("\n")
		writeSecurityBlock(b, apps, cfg)
	}

	b.WriteString("}\n\n")
}

// SessionLifetimeSeconds is the caddy-security JWT/session lifetime the
// portal issues (ADR-063). caddy-security's own default is 900 s.
const SessionLifetimeSeconds = 28800

// writeSecurityBlock writes the caddy-security configuration including the
// OAuth identity provider, authentication portal with user transforms,
// and per-app authorization policies.
func writeSecurityBlock(b *strings.Builder, apps []App, cfg GeneratorConfig) {
	b.WriteString("    security {\n")

	// Identity provider
	b.WriteString("        oauth identity provider google {\n")
	b.WriteString("            realm google\n")
	b.WriteString("            driver google\n")
	b.WriteString("            client_id {env.GOOGLE_CLIENT_ID}\n")
	b.WriteString("            client_secret {env.GOOGLE_CLIENT_SECRET}\n")
	b.WriteString("            scopes openid email profile\n")
	b.WriteString("        }\n\n")

	// Authentication portal
	fmt.Fprintf(b, "        authentication portal myportal {\n")
	b.WriteString("            enable identity provider google\n")
	fmt.Fprintf(b, "            cookie domain %s\n", cfg.BaseDomain)
	// Lax: a cross-SITE WebSocket handshake or fetch no longer carries the
	// session (the server also refuses cross-origin sockets before any side
	// effect; this closes the other half, audit 2026-09-13).
	fmt.Fprintf(b, "            cookie samesite lax\n")
	// Leading dot: go-authcrunch matches the redirect host with a bare
	// HasSuffix, so a bare domain trusted "evil<base>" as a post-login
	// redirect target — an open redirect on the portal (audit 2026-09-13).
	// ".<base>" is label-bounded; the app host <name>.<base> and the auth
	// host auth.<base> still match; the apex is not a served site.
	fmt.Fprintf(b, "            trust login redirect uri domain suffix .%s path prefix /\n", cfg.BaseDomain)
	// Session lifetime, set deliberately instead of inheriting the plugin's
	// 900 s default (BUG-001 made expiry visible: a toast and a reload every
	// 15 minutes of use). Eight hours — a working day. The lifetime is not
	// the revocation control: the styrman server re-checks the userstore on
	// every request, so removing a user takes effect at once; the trade is
	// how long a stolen cookie stays valid (ADR-063, operator 2026-09-04).
	fmt.Fprintf(b, "            crypto default token lifetime %d\n", SessionLifetimeSeconds)
	if cfg.JWTKey != "" {
		// Pin the token signing key so sessions survive a Caddy restart and
		// the portal + authorizers always agree (auto-generated keys reset).
		b.WriteString("            crypto key sign-verify {env.STYRMAN_JWT_KEY}\n")
	}

	// Write user transforms for role-gated apps
	for _, app := range apps {
		if app.Mode != ModeRoleGated {
			continue
		}

		// Platform superadmins get superadmin role on ALL apps
		for _, email := range cfg.SuperAdmins {
			if !containsEmail(app.SuperAdmins, email) {
				writeTransform(b, email, fmt.Sprintf("app/%s/superadmin", app.Hostname))
			}
		}
		// Per-app superadmins (highest privilege)
		for _, email := range app.SuperAdmins {
			writeTransform(b, email, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
		// Per-app admins
		for _, email := range app.Admins {
			writeTransform(b, email, fmt.Sprintf("app/%s/admin", app.Hostname))
		}
		// Per-app viewers
		for _, email := range app.Viewers {
			writeTransform(b, email, fmt.Sprintf("app/%s/viewer", app.Hostname))
		}
	}

	// For mode 2 (authenticated) apps, superadmins + default admins get roles
	for _, app := range apps {
		if app.Mode != ModeAuthenticated {
			continue
		}
		for _, email := range cfg.SuperAdmins {
			writeTransform(b, email, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
	}

	b.WriteString("        }\n\n")

	// Authorization policies (one per non-public app)
	for _, app := range apps {
		if app.Mode == ModePublic {
			continue
		}
		writeAuthzPolicy(b, app, cfg)
	}

	b.WriteString("    }\n")
}

// writeTransform writes a single transform user block.
func writeTransform(b *strings.Builder, email, role string) {
	b.WriteString("            transform user {\n")
	fmt.Fprintf(b, "                match email %s\n", email)
	fmt.Fprintf(b, "                action add role %s\n", role)
	b.WriteString("            }\n")
}

// writeAuthzPolicy writes an authorization policy for a single app.
func writeAuthzPolicy(b *strings.Builder, app App, cfg GeneratorConfig) {
	policyName := sanitizePolicyName(app.Hostname)
	fmt.Fprintf(b, "        authorization policy %s_policy {\n", policyName)
	// Point directly to Google OAuth to skip the portal login page
	fmt.Fprintf(b, "            set auth url https://%s/oauth2/google/\n", cfg.AuthDomain)
	if cfg.JWTKey != "" {
		b.WriteString("            crypto key verify {env.STYRMAN_JWT_KEY}\n")
	}

	switch app.Mode {
	case ModeAuthenticated:
		// Any authenticated user can access (authp/user for known domains, authp/guest for others)
		// If superadmins or default admins exist, include their roles in the access list too
		var roles []string
		if len(cfg.SuperAdmins) > 0 {
			roles = append(roles, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
		roles = append(roles, "authp/user", "authp/guest")
		fmt.Fprintf(b, "            allow roles %s\n", strings.Join(roles, " "))
	case ModeRoleGated:
		// Only specific roles can access
		var roles []string
		if len(app.SuperAdmins) > 0 || len(cfg.SuperAdmins) > 0 {
			roles = append(roles, fmt.Sprintf("app/%s/superadmin", app.Hostname))
		}
		roles = append(roles, fmt.Sprintf("app/%s/admin", app.Hostname))
		if len(app.Viewers) > 0 {
			roles = append(roles, fmt.Sprintf("app/%s/viewer", app.Hostname))
		}
		fmt.Fprintf(b, "            allow roles %s\n", strings.Join(roles, " "))
	}

	b.WriteString("            inject headers with claims\n")
	fmt.Fprintf(b, "        }\n\n")
}

// writeAppBlock writes a single site block for an app.
func writeAppBlock(b *strings.Builder, app App, cfg GeneratorConfig) {
	// Infrastructure containers get absolute FQDNs; user apps get <hostname>.<AppsDomain>
	var fqdn string
	if app.Hostname == ShellHostname {
		fqdn = cfg.ShellDomain
	} else {
		fqdn = fmt.Sprintf("%s.%s", app.Hostname, cfg.AppsDomain)
	}

	// Comment with mode
	modeStr := "public"
	if app.Mode == ModeAuthenticated {
		modeStr = "authenticated"
	} else if app.Mode == ModeRoleGated {
		modeStr = "role-gated"
	}
	fmt.Fprintf(b, "# %s (%s, %d rps)\n", app.Hostname, modeStr, app.RPS)

	fmt.Fprintf(b, "%s {\n", fqdn)

	// Rate limiting
	fmt.Fprintf(b, "    rate_limit {\n")
	fmt.Fprintf(b, "        zone %s_rl {\n", sanitizePolicyName(app.Hostname))
	fmt.Fprintf(b, "            key {remote_host}\n")
	fmt.Fprintf(b, "            events %d\n", app.RPS)
	fmt.Fprintf(b, "            window 1s\n")
	fmt.Fprintf(b, "        }\n")
	fmt.Fprintf(b, "    }\n")

	if app.Mode == ModePublic {
		// Public + unauthenticated: strip any client-supplied identity / ingress
		// headers before proxying so they can't be forwarded upstream and spoof
		// anything downstream (M24 — a public preview carries no identity), then
		// set the authentic public role.
		for _, h := range []string{HeaderEmail, HeaderUser, HeaderRole, HeaderSubject, HeaderIngress} {
			fmt.Fprintf(b, "    request_header -%s\n", h)
		}
		// A public app is someone's container on the base domain, where the
		// portal's session cookie is sent too: cut that one cookie out before
		// proxying, as the preview block does (security review, 2026-09-13).
		fmt.Fprintf(b, "    request_header Cookie \"(?:^|;\\s*)%s=[^;]*\" \"\"\n", AuthCookieName)
		fmt.Fprintf(b, "    request_header %s \"%s\"\n", HeaderRole, RolePublic)
		fmt.Fprintf(b, "    reverse_proxy %s:%d\n", app.ContainerIP, app.Port)
	} else {
		// Use route{} for explicit handler ordering:
		// authorize → set clean headers → strip upstream headers → reverse_proxy
		policyName := sanitizePolicyName(app.Hostname)
		b.WriteString("    route {\n")
		// Defense in depth: strip any CLIENT-supplied copies of the upstream
		// claim headers BEFORE the authorizer injects the authentic ones, so a
		// spoofed X-Token-User-Email can never win the placeholder below (guards
		// against caddy-security using Header.Add rather than Set).
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderEmail)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderName)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderRoles)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderSub)
		fmt.Fprintf(b, "        authorize with %s_policy\n", policyName)

		// Set clean identity headers from caddy-security's injected upstream headers
		fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderEmail, UpstreamHeaderEmail)
		fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderUser, UpstreamHeaderName)
		fmt.Fprintf(b, "        request_header %s \"{http.request.header.%s}\"\n", HeaderSubject, UpstreamHeaderSub)

		if app.Mode == ModeRoleGated {
			// Set role: viewer first, then admin, then superadmin overwrites (highest wins)
			fmt.Fprintf(b, "        @%s_viewer header_regexp %s \"app/%s/%s\"\n", policyName, UpstreamHeaderRoles, app.Hostname, RoleViewer)
			fmt.Fprintf(b, "        request_header @%s_viewer %s \"%s\"\n", policyName, HeaderRole, RoleViewer)
			fmt.Fprintf(b, "        @%s_admin header_regexp %s \"app/%s/%s\"\n", policyName, UpstreamHeaderRoles, app.Hostname, RoleAdmin)
			fmt.Fprintf(b, "        request_header @%s_admin %s \"%s\"\n", policyName, HeaderRole, RoleAdmin)
			fmt.Fprintf(b, "        @%s_superadmin header_regexp %s \"app/%s/%s\"\n", policyName, UpstreamHeaderRoles, app.Hostname, RoleSuperAdmin)
			fmt.Fprintf(b, "        request_header @%s_superadmin %s \"%s\"\n", policyName, HeaderRole, RoleSuperAdmin)
		} else {
			// Authenticated mode: any Google user gets role "user"
			fmt.Fprintf(b, "        request_header %s \"%s\"\n", HeaderRole, RoleUser)
		}

		// Strip caddy-security internal headers
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderEmail)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderName)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderRoles)
		fmt.Fprintf(b, "        request_header -%s\n", UpstreamHeaderSub)

		// Ingress origin proof: strip any client-supplied token, then set the
		// shared one so the upstream can reject requests that reach it
		// directly (e.g. a container on a shared bridge spoofing X-Caddy-Email).
		// The strip is unconditional so a token-less deploy still can't relay
		// a forged header.
		fmt.Fprintf(b, "        request_header -%s\n", HeaderIngress)
		if cfg.IngressToken != "" {
			fmt.Fprintf(b, "        request_header %s %q\n", HeaderIngress, cfg.IngressToken)
		}

		fmt.Fprintf(b, "        reverse_proxy %s:%d\n", app.ContainerIP, app.Port)
		b.WriteString("    }\n")
	}

	b.WriteString("}\n\n")
}

// sanitizePolicyName converts a hostname into a valid Caddy policy name.
// Replaces hyphens and dots with underscores.
func sanitizePolicyName(hostname string) string {
	s := strings.ReplaceAll(hostname, "-", "_")
	s = strings.ReplaceAll(s, ".", "_")
	return s
}

// containsEmail checks if an email exists in a slice.
func containsEmail(emails []string, target string) bool {
	for _, e := range emails {
		if strings.EqualFold(e, target) {
			return true
		}
	}
	return false
}
